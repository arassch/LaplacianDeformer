#!/bin/bash
# Builds web/deformer.html: one self-contained page with the Deformer compiled to WebAssembly.
#
# Requirements: Emscripten (em++ on PATH), Eigen 3 headers, Node.js, and the ElasticFEM sources
# (TriMesh + LinearAlgebra).
#
#   ELASTICFEM=/path/to/ElasticFEM ./build.sh
#
# Optional:
#   EIGEN=/path/to/eigen3              (default: /usr/include/eigen3, or Homebrew's on macOS)
#   KITTEN=/path/to/kitten.obj         embed a second mesh for demo 3 (otherwise load it with "Load OBJ")
set -e
cd "$(dirname "$0")"
ROOT=..
: "${ELASTICFEM:?Set ELASTICFEM to the ElasticFEM folder (containing TriMesh/ and LinearAlgebra/)}"
if [ -z "$EIGEN" ]; then
  if [ -d /usr/include/eigen3 ]; then EIGEN=/usr/include/eigen3
  elif command -v brew >/dev/null; then EIGEN="$(brew --prefix eigen)/include/eigen3"; fi
fi
[ -d "$EIGEN/Eigen" ] || { echo "Eigen not found; set EIGEN=/path/to/eigen3"; exit 1; }
command -v em++ >/dev/null || { echo "em++ not found; install Emscripten"; exit 1; }
[ -d node_modules ] || npm install

mkdir -p build/obj
FL="-O2 -w -std=gnu++11 -Ulinux -Icompat -I$ELASTICFEM/LinearAlgebra/inc -I$ELASTICFEM/TriMesh/inc -I$EIGEN"

# 1) Extract the Deformer class verbatim from ../deform.h and ../deform.cpp.
#    Only addition: a friend declaration so the sparse fast path (api.cpp) can read m_Ls, m_M, m_Ks, m_Kb.
{ echo '// AUTO-GENERATED by build.sh from deform.h + deform.cpp (Deformer class only) - do not edit'
  printf '#include <TriMesh.h>\n#include <TriVertex.h>\n#include <Eigen/Core>\n#include <Eigen/Dense>\n#include <Eigen/Sparse>\n#include <Eigen/SparseCholesky>\n#include <set>\n#include <map>\n#include <math.h>\nusing namespace std;\nstruct FastSolve;\n'
  sed -n '/^class Deformer/,/^};/p' $ROOT/deform.h | sed 's/^{$/{\n    friend struct FastSolve;/'
  sed -n '/^void Deformer::setKs/,$p' $ROOT/deform.cpp; } > build/deformer_extracted.cpp

# 2) Compile ElasticFEM (LinearAlgebra + TriMesh) and the C API with Emscripten.
for f in $(sed -n '/^SOURCES/,/^$/p' "$ELASTICFEM/LinearAlgebra/LinearAlgebra.pro" | grep -o 'src/[A-Za-z0-9]*\.cpp'); do
  o=build/obj/la_$(basename $f .cpp).o; [ "$o" -nt "$ELASTICFEM/LinearAlgebra/$f" ] || em++ -c $FL "$ELASTICFEM/LinearAlgebra/$f" -o $o
done
for n in Reader Subdivision TriCirculator TriEdge TriFace TriMesh TriVertex Writer; do
  o=build/obj/tm_$n.o; [ "$o" -nt "$ELASTICFEM/TriMesh/src/$n.cpp" ] || em++ -c $FL "$ELASTICFEM/TriMesh/src/$n.cpp" -o $o
done
em++ -c $FL -Ibuild api.cpp -o build/obj/api.o
em++ -O2 build/obj/*.o -o build/deformer.js -sMODULARIZE=1 -sEXPORT_NAME=createDeformer -sSINGLE_FILE=1 \
  -sALLOW_MEMORY_GROWTH=1 -sMAXIMUM_MEMORY=4GB -sLEGACY_GL_EMULATION=1 -sENVIRONMENT=web,node \
  -sEXPORTED_RUNTIME_METHODS='["FS","ccall","cwrap","HEAPF32","HEAP32"]' -sEXPORTED_FUNCTIONS='["_malloc","_free"]'

# 3) Bundle the viewer and inline everything into one HTML file.
npx esbuild main.js --bundle --minify --format=iife --target=es2020 --outfile=build/main.bundle.js --log-level=error
KITTEN="$KITTEN" python3 - <<'EOF'
import json, os
shell = open('shell.html').read(); dj = open('build/deformer.js').read(); mb = open('build/main.bundle.js').read()
data = "window.DEFAULT_OBJ=" + json.dumps(open('plane.obj').read()) + ";"
k = os.environ.get('KITTEN')
if k: data += "window.KITTEN_OBJ=" + json.dumps(open(k).read()) + ";"
for s in (dj, mb): assert '</script' not in s.lower()
open('deformer.html', 'w').write(shell.replace('<!--INLINE-->', "<script>" + data + "</script>\n<script>" + dj + "</script>\n<script>" + mb + "</script>"))
EOF
ls -la deformer.html
